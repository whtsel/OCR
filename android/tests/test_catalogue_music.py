    def test_label_channel_resolves_more_than_one_black_sherif_release(self):
        # Public EMPIRE art-track metadata, not a live provider or download test.
        # https://www.youtube.com/watch?v=XRnLYE4WN6I
        # https://www.youtube.com/watch?v=f1YjlWCgc2U
        for title, album, seconds, provider_length, video in (
                ('The Homeless Song', 'The Villain I Never Was', 164, 165, 'XRnLYE4WN6I'),
                ('The Victory Song', 'IRON BOY', 175, 175, 'f1YjlWCgc2U')):
            with self.subTest(title=title):
                record = (title, 'Black Sherif', album, seconds)
                published = dict(id=video, title=title, channel='Black Sherif Music',
                                 channel_id='UC1IZ-tDYT2IrA-__AMqNOHA', duration=provider_length,
                                 description=f'Provided to YouTube by EMPIRE Distribution\n\n{title} · Black Sherif\n\n'
                                             f'{album}\n\n℗ Blacko Management / EMPIRE\n\nAuto-generated by YouTube.',
                                 live_status='not_live', availability='public')
                # Several plausible titles are ranked before the real label result by the provider.
                similar = [dict(published, id=f'REPOST{n:05d}', channel='Black Sherif', channel_id='other') for n in range(4)]
                engine = Engine(similar + [published], {item['id']: item for item in similar + [published]})
                self.assertTrue(resolver.prepare(engine, *record, lambda _: None, LookupError))
                self.assertEqual(engine.inspections, [video])
                self.assertEqual(engine.downloads, [video])
                for change in (dict(channel_id='other', channel_is_verified=True), dict(duration=36),
                               dict(track=title + ' (Remix)'), dict(artists=['Another Artist']), dict(availability='needs_auth'),
                               dict(description=published['description'].replace('EMPIRE Distribution', 'Another Distributor')),
                               dict(description=published['description'].replace(album, 'A Different Release')),
                               dict(description=published['description'].replace('· Black Sherif', '· Someone Else'))):
                    self.assertFalse(resolver.matches(dict(published, **change), video, *record), change)
                self.assertFalse(resolver.matches(published, video, title, 'Black Sherif', 'Some Other Album', seconds))

