class LookupError(Exception):
    pass


class Engine:
    def __init__(self, rows, videos):
        self.rows = rows
        self.videos = videos
        self.downloads = []
        self.inspections = []
        self.queries = []

    def extract_info(self, url, *, download, process=True):
        if download:
            raise AssertionError('A metadata lookup must never download')
        if url.startswith('ytsearch'):
            assert not process
            query = url.split(':', 1)[1]
            self.queries.append(query)
            return {'entries': self.rows.get(query, []) if isinstance(self.rows, dict) else self.rows}
        assert not process
        video = url.split('=')[-1]
        self.inspections.append(video)
        if video not in self.videos:
            raise LookupError(video)
        result = self.videos[video]
        if isinstance(result, Exception):
            raise result
        return result

    def process_ie_result(self, info, *, download):
        assert download
        self.downloads.append(info['id'])


class TestSelection(unittest.TestCase):
    def test_requires_release_credits_length_and_publisher(self):
        self.assertTrue(resolver.matches(official, official['id'], *track))
        for change in (dict(album='A different release'), dict(track='Taste - Cover'), dict(duration=30),
                       dict(title='Taste (Radio Edit)'), dict(artists=['Other Artist']), dict(channel='A reuploader'),
                       dict(description='Auto-generated by YouTube.'), dict(availability='needs_auth'),
                       dict(is_live=True), dict(_type='playlist'), dict(id='NOTORIGINAL')):
            with self.subTest(change=change):
                self.assertFalse(resolver.matches(dict(official, **change), official['id'], *track))

    def test_search_never_downloads_a_cover_and_checks_no_more_than_four(self):
        wrong = dict(official, id='NOTORIGINAL', channel_is_verified=True, album='Tribute Album')
        rows = [wrong, dict(official, title='Taste (Cover)'), official]
        engine = Engine(rows, {row['id']: row for row in (wrong, official)})
        marks = []
        self.assertTrue(resolver.prepare(engine, *track, marks.append, LookupError))
        self.assertEqual(engine.inspections, ['NOTORIGINAL', 'ORIGINAL123'])
        self.assertEqual(engine.downloads, ['ORIGINAL123'])
        self.assertEqual(engine.downloads, marks)
        engine = Engine([dict(wrong, id=f'fake{idx:07d}') for idx in range(20)], {})
        with self.assertRaises(LookupError):
            resolver.prepare(engine, *track, marks.append, LookupError)
        self.assertEqual(len(engine.inspections), resolver.INSPECTIONS)
        self.assertFalse(engine.downloads)

    def test_rate_limit_stops_candidate_inspection(self):
        wrong = dict(official, id='NOTORIGINAL')
        engine = Engine([wrong, official], {'NOTORIGINAL': LookupError('HTTP Error 429'), 'ORIGINAL123': official})
        with self.assertRaisesRegex(LookupError, '429'):
            resolver.prepare(engine, *track, lambda video: self.fail('must not fetch'), LookupError)
        self.assertEqual(engine.inspections, ['NOTORIGINAL'])
        self.assertFalse(engine.downloads)

    def test_alternate_wording_finds_exact_edition_with_reordered_credits(self):
        record = ('After Midnight', 'Singer A feat. Singer B', 'Night Album', 180)
        cover = dict(official, id='WRONGED1111', title='After Midnight (Official Audio)',
                     track=record[0], artists=['Singer A', 'Singer B'], channel='Singer B', channel_is_verified=True,
                     duration=180, album='Cover Album')
        right = dict(cover, id='RIGHTED1111', title='Singer B & Singer A — After Midnight [Official Video]',
                     artists=['Singer B', 'Singer A'], album=record[2])
        engine = Engine({f'{record[1]} {record[0]} {record[2]}': [cover],
                         f'{record[1]} {record[0]}': [cover, right]},
                        {cover['id']: cover, right['id']: right})
        self.assertTrue(resolver.prepare(engine, *record, lambda _: None, LookupError))
        self.assertEqual(engine.inspections, [cover['id'], right['id']])
        self.assertEqual(engine.downloads, [right['id']])
        self.assertEqual(len(engine.queries), 2)
        for change in (dict(album=None), dict(artists=['Singer B', 'Wrong Artist']),
                       dict(title='Singer B & Singer A — After Midnight (Slowed)'),
                       dict(title='Singer B & Singer A — After Midnight (Radio Edit)'),
                       dict(channel='Other Channel'), dict(duration=200)):
            self.assertFalse(resolver.matches(dict(right, **change), right['id'], *record), change)

    def test_unpinned_editions_are_resolved_from_the_album_and_matching_publisher_evidence(self):
        # The detailed response can lack the owner badge and flatten the credit list.
        # Fixtures are invented; none can use a published or remembered ID.
        for i, (title, artist, album, seconds) in enumerate((
                ('Low Orbit', 'North Signal & Vela', 'Night Transit', 183),
                ('Cerca del Río', 'Luz & Mar', 'Otras Orillas', 204),
                ('星空', 'ミナ & ソラ', '夜の便り', 146))):
            with self.subTest(title=title):
                record = (title, artist, album, seconds)
                channel_id = f'UC{i:022d}'
                lead, guest = artist.split(' & ')
                exact = dict(id=f'RELEASE{i:04d}', title=title, track=title, album=album,
                             # A provider Artist badge is one string and may put the guest first.
                             artists=[f'{guest} · {lead}'], duration=seconds, channel=lead,
                             channel_id=channel_id, availability='public', live_status='not_live')
                self.assertIsNone(resolver.published(*record))
                listing = dict(id=exact['id'], title=title, duration=seconds, channel=lead,
                               channel_id=channel_id, ie_key='Youtube', channel_is_verified=True)
                lookalikes = [dict(listing, id=f'REPOST{i}{n:04d}', channel_is_verified=None) for n in range(8)]
                primary = f'{artist} {title} {album}'
                engine = Engine({primary: lookalikes + [listing]}, {exact['id']: exact})
                self.assertTrue(resolver.prepare(engine, *record, lambda _: None, LookupError))
                self.assertEqual(engine.queries, [primary])
                self.assertEqual(engine.inspections, [exact['id']])
                self.assertEqual(engine.downloads, [exact['id']])
                # Borrow no evidence from a different uploader, video or extractor.
                for change in (dict(channel_id='UC' + 'x'*22), dict(id='DIFFERENT12'),
                               dict(ie_key='Other'), dict(channel_is_verified=False)):
                    self.assertFalse(resolver.matches(exact, exact['id'], *record, dict(listing, **change)))
                for change in (dict(album=album + ' (Deluxe)'), dict(artists=[lead]),
                               dict(title=title + ' (Live)'), dict(availability='premium_only'),
                               dict(duration=seconds+7), dict(channel_is_verified=False)):
                    self.assertFalse(resolver.matches(dict(exact, **change), exact['id'], *record, listing))

