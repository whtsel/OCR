"""Prove source selection using controlled YouTube-shaped metadata, with no network or audio."""
import importlib.util
from pathlib import Path
import unittest

script = Path(__file__).resolve().parents[1] / 'app/src/musicHelper/res/raw/catalogue_music.py'
spec = importlib.util.spec_from_file_location('catalogue_music', script)
resolver = importlib.util.module_from_spec(spec)
spec.loader.exec_module(resolver)

track = ('Taste', 'Sabrina Carpenter', "Short n' Sweet", 157)
official = dict(id='ORIGINAL123', title='Taste', track='Taste', album="Short n' Sweet", artists=['Sabrina Carpenter'],
                channel='Sabrina Carpenter - Topic', description='Provided to YouTube by Label\nAuto-generated by YouTube.',
                duration=157, live_status='not_live', availability='public')


class LookupError(Exception):
    pass


class Engine:
    def __init__(self, rows, videos):
        self.params = {}
        self.rows = rows
        self.videos = videos
        self.downloads = []
        self.inspections = []

    def extract_info(self, url, *, download, process=True):
        if download:
            raise AssertionError('A metadata lookup must never download')
        if url.startswith('ytsearch'):
            assert self.params['extract_flat'] == 'in_playlist'
            return {'entries': self.rows}
        assert not process
        video = url.split('=')[-1]
        self.inspections.append(video)
        if video not in self.videos:
            raise LookupError(video)
        return self.videos[video]

    def process_ie_result(self, info, *, download):
        assert download
        self.downloads.append(info['id'])


class TestSelection(unittest.TestCase):
    def test_requires_release_credits_length_and_publisher(self):
        self.assertTrue(resolver.matches(official, official['id'], *track))
        for change in (dict(album='A different release'), dict(track='Taste - Cover'), dict(duration=30),
                       dict(title='Taste (Radio Edit)'), dict(artists=['Other Artist']), dict(channel='A reuploader'),
                       dict(description='Auto-generated by YouTube.'), dict(availability='needs_auth'),
                       dict(is_live=True), dict(_type='playlist'), dict(id='NOTORIGINAL')):
            with self.subTest(change=change):
                self.assertFalse(resolver.matches(dict(official, **change), official['id'], *track))

    def test_search_never_downloads_a_cover_and_checks_no_more_than_four(self):
        wrong = dict(official, id='NOTORIGINAL', channel_is_verified=True, album='Tribute Album')
        rows = [wrong, dict(official, title='Taste (Cover)'), official]
        engine = Engine(rows, {row['id']: row for row in (wrong, official)})
        marks = []
        self.assertTrue(resolver.prepare(engine, *track, marks.append, LookupError))
        self.assertEqual(engine.inspections, ['NOTORIGINAL', 'ORIGINAL123'])
        self.assertEqual(engine.downloads, ['ORIGINAL123'])
        self.assertEqual(engine.downloads, marks)
        engine = Engine([dict(wrong, id=f'fake{idx:07d}') for idx in range(20)], {})
        self.assertFalse(resolver.prepare(engine, *track, marks.append, LookupError))
        self.assertEqual(len(engine.inspections), resolver.INSPECTIONS)
        self.assertFalse(engine.downloads)

    def test_non_latin_recording_is_supported(self):
        info = dict(official, title='夜に駆ける', track='夜に駆ける', artists=['YOASOBI'], album='THE BOOK',
                    channel='YOASOBI', channel_is_verified=True, duration=261)
        self.assertTrue(resolver.matches(info, info['id'], '夜に駆ける', 'YOASOBI', 'The Book', 261))


if __name__ == '__main__':
    unittest.main()
