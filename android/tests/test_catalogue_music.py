"""Prove source selection using controlled YouTube-shaped metadata, with no network or audio."""
import importlib.util
from pathlib import Path
import unittest

script = Path(__file__).resolve().parents[1] / 'app/src/musicHelper/res/raw/catalogue_music.py'
spec = importlib.util.spec_from_file_location('catalogue_music', script)
resolver = importlib.util.module_from_spec(spec)
spec.loader.exec_module(resolver)

track = ('Taste', 'Sabrina Carpenter', "Short n' Sweet", 157)
official = dict(id='ORIGINAL123', title='Taste', track='Taste', album="Short n' Sweet", artists=['Sabrina Carpenter'],
                channel='Sabrina Carpenter - Topic', description='Provided to YouTube by Label\nAuto-generated by YouTube.',
                duration=157, live_status='not_live', availability='public')


class LookupError(Exception):
    pass


class Engine:
    def __init__(self, rows, videos):
        self.rows = rows
        self.videos = videos
        self.downloads = []
        self.inspections = []
        self.queries = []

    def extract_info(self, url, *, download, process=True):
        if download:
            raise AssertionError('A metadata lookup must never download')
        if url.startswith('ytsearch'):
            assert not process
            query = url.split(':', 1)[1]
            self.queries.append(query)
            return {'entries': self.rows.get(query, []) if isinstance(self.rows, dict) else self.rows}
        assert not process
        video = url.split('=')[-1]
        self.inspections.append(video)
        if video not in self.videos:
            raise LookupError(video)
        result = self.videos[video]
        if isinstance(result, Exception):
            raise result
        return result

    def process_ie_result(self, info, *, download):
        assert download
        self.downloads.append(info['id'])


class TestSelection(unittest.TestCase):
    def test_requires_release_credits_length_and_publisher(self):
        self.assertTrue(resolver.matches(official, official['id'], *track))
        for change in (dict(album='A different release'), dict(track='Taste - Cover'), dict(duration=30),
                       dict(title='Taste (Radio Edit)'), dict(artists=['Other Artist']), dict(channel='A reuploader'),
                       dict(description='Auto-generated by YouTube.'), dict(availability='needs_auth'),
                       dict(is_live=True), dict(_type='playlist'), dict(id='NOTORIGINAL')):
            with self.subTest(change=change):
                self.assertFalse(resolver.matches(dict(official, **change), official['id'], *track))

    def test_search_never_downloads_a_cover_and_checks_no_more_than_four(self):
        wrong = dict(official, id='NOTORIGINAL', channel_is_verified=True, album='Tribute Album')
        rows = [wrong, dict(official, title='Taste (Cover)'), official]
        engine = Engine(rows, {row['id']: row for row in (wrong, official)})
        marks = []
        self.assertTrue(resolver.prepare(engine, *track, marks.append, LookupError))
        self.assertEqual(engine.inspections, ['NOTORIGINAL', 'ORIGINAL123'])
        self.assertEqual(engine.downloads, ['ORIGINAL123'])
        self.assertEqual(engine.downloads, marks)
        engine = Engine([dict(wrong, id=f'fake{idx:07d}') for idx in range(20)], {})
        with self.assertRaises(LookupError):
            resolver.prepare(engine, *track, marks.append, LookupError)
        self.assertEqual(len(engine.inspections), resolver.INSPECTIONS)
        self.assertFalse(engine.downloads)

    def test_rate_limit_stops_candidate_inspection(self):
        wrong = dict(official, id='NOTORIGINAL')
        engine = Engine([wrong, official], {'NOTORIGINAL': LookupError('HTTP Error 429'), 'ORIGINAL123': official})
        with self.assertRaisesRegex(LookupError, '429'):
            resolver.prepare(engine, *track, lambda video: self.fail('must not fetch'), LookupError)
        self.assertEqual(engine.inspections, ['NOTORIGINAL'])
        self.assertFalse(engine.downloads)

    def test_alternate_wording_finds_exact_edition_with_reordered_credits(self):
        record = ('After Midnight', 'Singer A feat. Singer B', 'Night Album', 180)
        cover = dict(official, id='WRONGED1111', title='After Midnight (Official Audio)',
                     track=record[0], artists=['Singer A', 'Singer B'], channel='Singer B', channel_is_verified=True,
                     duration=180, album='Cover Album')
        right = dict(cover, id='RIGHTED1111', title='Singer B & Singer A — After Midnight [Official Video]',
                     artists=['Singer B', 'Singer A'], album=record[2])
        engine = Engine({f'{record[1]} {record[0]}': [cover],
                         f'{record[0]} {record[1]} {record[2]} official audio': [cover, right]},
                        {cover['id']: cover, right['id']: right})
        self.assertTrue(resolver.prepare(engine, *record, lambda _: None, LookupError))
        self.assertEqual(engine.inspections, [cover['id'], right['id']])
        self.assertEqual(engine.downloads, [right['id']])
        self.assertEqual(len(engine.queries), 2)
        for change in (dict(album=None), dict(artists=['Singer B', 'Wrong Artist']),
                       dict(title='Singer B & Singer A — After Midnight (Slowed)'),
                       dict(title='Singer B & Singer A — After Midnight (Radio Edit)'),
                       dict(channel='Other Channel'), dict(duration=200)):
            self.assertFalse(resolver.matches(dict(right, **change), right['id'], *record), change)

    def test_remembered_id_has_no_search_when_valid_but_stale_metadata_cannot_play(self):
        engine = Engine([], {official['id']: official})
        self.assertTrue(resolver.prepare(engine, *track, lambda _: None, LookupError, official['id']))
        self.assertEqual(engine.queries, [])
        self.assertEqual(engine.downloads, [official['id']])
        stale = dict(official, id='STALEID1111', album='Alternate release')
        engine = Engine([stale, official], {stale['id']: stale, official['id']: official})
        self.assertTrue(resolver.prepare(engine, *track, lambda _: None, LookupError, stale['id']))
        self.assertEqual(engine.inspections, [stale['id'], official['id']])
        self.assertEqual(engine.downloads, [official['id']])
        engine = Engine([stale], {stale['id']: stale})
        self.assertFalse(resolver.prepare(engine, *track, lambda _: self.fail('must not mark'), LookupError, stale['id']))
        self.assertEqual(engine.downloads, [])

    def test_offline_lookup_only_returns_the_verified_id(self):
        wrong = dict(official, id='NOTORIGINAL', album='A different release')
        engine = Engine([wrong, official], {wrong['id']: wrong, official['id']: official})
        marks = []
        self.assertTrue(resolver.prepare(engine, *track, marks.append, LookupError, download=False))
        self.assertEqual(marks, ['ORIGINAL123'])
        self.assertEqual(engine.inspections, ['NOTORIGINAL', 'ORIGINAL123'])
        self.assertFalse(engine.downloads)

    def test_live_album_track_can_have_a_shorter_public_upload_label(self):
        record = ('Goodness of God (Live)', 'CeCe Winans', 'Believe For It', 298)
        # Controlled example for a v90 catalogue row, not a live provider assertion.
        result = dict(official, title='CeCe Winans - Goodness of God (Official Audio)',
                      track=None, album=None, artists=None, channel='CeCe Winans - Topic', duration=298,
                      description='Provided to YouTube by Label\n\nGoodness of God (Live) · CeCe Winans\n\n'
                                  'Believe For It (Live)\n\n℗ Label\n\nAuto-generated by YouTube.')
        engine = Engine([result], {result['id']: result})
        self.assertTrue(resolver.prepare(engine, *record, lambda _: None, LookupError))
        self.assertEqual(engine.downloads, [result['id']])
        for change in (dict(track='Goodness of God'), dict(album='A tribute album'), dict(duration=304.6),
                       dict(is_live=True), dict(live_status='is_upcoming'), dict(channel='Copy of CeCe Winans - Topic'),
                       dict(title='Goodness of God (Studio Version)'), dict(description='')):
            self.assertFalse(resolver.matches(dict(result, **change), result['id'], *record), change)

    def test_ended_live_recording_requires_the_live_catalogue_edition(self):
        record = ('Someday (Live)', 'Kirk Franklin', 'I Am What I Am', 396)
        result = dict(official, title='Someday [Live] [Official Audio]', track='Someday (Live)',
                      album=record[2], artists=['Kirk Franklin'], channel='KirkFranklinVEVO', channel_is_verified=True,
                      duration=396, was_live=True, live_status='was_live')
        self.assertTrue(resolver.matches(result, result['id'], *record))
        self.assertFalse(resolver.matches(result, result['id'], 'Someday', *record[1:]))
        self.assertFalse(resolver.matches(dict(result, is_live=True), result['id'], *record))
        self.assertFalse(resolver.matches(dict(result, duration=2300), result['id'], *record))

    def test_featured_credits_can_move_into_the_track_tag_without_losing_the_studio_version(self):
        title = 'Breathe (feat. Chandler Moore, Jonathan McReynolds, DOE & Mav City Gospel Choir) [Studio Version]'
        record = (title, 'Maverick City Music', 'Breathe (feat. Mav City Gospel Choir) - EP', 326)
        result = dict(official, title='Breathe (Studio Version)', track=title,
                      album='Breathe - EP', artists=['Maverick City Music'], channel='Maverick City Music - Topic', duration=326)
        self.assertTrue(resolver.matches(result, result['id'], *record))
        split = dict(result, track='Breathe (Studio Version)', artists=['Maverick City Music', 'DOE', 'Mav City Gospel Choir',
                                                                       'Chandler Moore', 'Jonathan McReynolds'])
        self.assertTrue(resolver.matches(split, result['id'], *record))
        for wrong in (dict(split, artists=['Maverick City Music', 'DOE']), dict(split, track='Breathe (Live)'),
                      dict(split, album='Breathe (Deluxe)'), dict(split, title='Breathe (Remix)'), dict(split, duration=484)):
            self.assertFalse(resolver.matches(wrong, result['id'], *record))

    def test_bot_check_does_not_try_an_alternate_query(self):
        engine = Engine([official], {official['id']: LookupError('Sign in to confirm you are not a bot')})
        with self.assertRaisesRegex(LookupError, 'not a bot'):
            resolver.prepare(engine, *track, lambda _: self.fail('must not fetch'), LookupError)
        self.assertEqual(len(engine.queries), 1)
        self.assertEqual(engine.downloads, [])

    def test_non_latin_recording_is_supported(self):
        info = dict(official, title='夜に駆ける', track='夜に駆ける', artists=['YOASOBI'], album='THE BOOK',
                    channel='YOASOBI', channel_is_verified=True, duration=261)
        self.assertTrue(resolver.matches(info, info['id'], '夜に駆ける', 'YOASOBI', 'The Book', 261))


if __name__ == '__main__':
    unittest.main()
